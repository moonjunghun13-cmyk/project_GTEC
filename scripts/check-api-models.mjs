import assert from 'node:assert/strict'
import {productModel,memberModel,orderModel,reviewModel} from '../src/services/backendModels.js'
const product=productModel({id:42,name:'서버 상품',category:'RAM',specification:'DDR5',thumbnailUrl:'/test.png',imageUrls:['/one.png','/two.png'],stock:5,status:'ACTIVE',price:1000})
assert.equal(product.productId,'42')
assert.equal(product.category,'메모리')
assert.equal(product.gallery[1].image,'/two.png')
assert.equal(product.details.specifications[2][1],'DDR5')
assert.equal(productModel({...product,id:42,status:'SOLD_OUT',stock:3}).stock,0)
assert.equal(memberModel({id:3,loginId:'user3',status:'KICKED'}).status,'정지')
const order=orderModel({orderId:5,status:'COMPLETED',createdAt:'2026-11-18T10:00:00',totalAmount:2000,shippingName:'구매자',items:[{orderItemId:7,productId:42,quantity:2,unitPrice:1000}]},[product],{invoiceNumber:'123'},[])
assert.equal(order.status,'구매 확정')
assert.equal(order.items[0].orderItemId,7)
assert.equal(order.items[0].productId,'42')
assert.equal(order.items[0].name,'서버 상품')
assert.equal(order.tracking,'123')
assert.equal(reviewModel({id:8,productId:42,content:'리뷰'}).body,'리뷰')
assert.equal(reviewModel({id:8,productId:42,content:'리뷰'}).sentiment,null)
console.log('API model contracts passed')
